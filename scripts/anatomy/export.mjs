/**
 * Static art for the lazy section figures (NAJ-897, page weight).
 *
 *   node scripts/anatomy/export.mjs           write public/figures/*.svg and the manifest
 *   node scripts/anatomy/export.mjs --check   exit 1 if the committed files are not what the geometry draws now
 *
 * The four section figures (omni desk, knowledge press, Gulf vault, credit
 * meter) no longer ship their drawings inline: the homepage carried every SVG
 * twice, once as HTML and once in the React server payload. This script draws
 * each one from the SAME modules the verification builds import, writes it as
 * a content-hashed, standalone SVG under public/figures/ (served with a
 * one-year immutable cache header, next.config.ts), and records the URLs in
 * src/components/anatomy/lazy/assets.ts. The figures fetch their file when
 * they come near the viewport (lazy/useLazyArt.ts).
 *
 * Run it after any change to a figure's geometry, model words or order, and
 * commit the SVGs and the manifest together. `--check` is the guard.
 */
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, readdirSync, unlinkSync, writeFileSync } from "node:fs";
import { registerHooks } from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, "..", "..");
const SRC = join(ROOT, "src");
const FIGS = join(SRC, "components", "anatomy");
const OUT = join(ROOT, "public", "figures");
const MANIFEST = join(FIGS, "lazy", "assets.ts");
const CHECK = process.argv.includes("--check");
process.removeAllListeners("warning"); // Node notes that the site's .ts files are typeless ESM; the output is what matters here

/* The site's modules use extensionless and "@/" imports (Next resolves them); teach Node the same. */
registerHooks({
  resolve(specifier, context, next) {
    let target = specifier;
    if (target.startsWith("@/")) target = pathToFileURL(join(SRC, target.slice(2))).href;
    try {
      return next(target, context);
    } catch (error) {
      const base = target.startsWith("file:") ? target : context.parentURL ? new URL(target, context.parentURL).href : target;
      for (const ext of [".ts", ".tsx", "/index.ts"]) {
        const url = base + ext;
        if (existsSync(fileURLToPath(url))) return next(url, context);
      }
      throw error;
    }
  },
});

const load = (path) => import(pathToFileURL(join(FIGS, path)).href);
const UID = "ANXUID"; // the same token as UID_TOKEN in lazy/useLazyArt.ts
const LOCALES = ["ar", "en"];

const wrap = (body, width, height, extra = "") =>
  `<svg xmlns="http://www.w3.org/2000/svg" class="iso-svg${extra ? ` ${extra}` : ""}" viewBox="0 0 ${width} ${height}" aria-hidden="true" focusable="false">${body}</svg>\n`;

const kb = await load("kb-press/geometry.ts");
const vault = await load("vault/geometry.ts");
const vaultView = await load("vault/view.ts");
const omni = await load("omni-desk/markup.ts");
const meter = await load("credit-meter/scene.ts");

/** Every asset: [figure, locale, svg]. The knowledge press draws no words, so one file serves both locales. */
const art = [];
{
  const clip = `${kb.CLIP_ID}-${UID}`;
  const body = kb.BODY.replace(`id="${kb.CLIP_ID}"`, `id="${clip}"`).replace(`url(#${kb.CLIP_ID})`, `url(#${clip})`);
  const svg = wrap(body, kb.VIEW.width, kb.VIEW.height);
  for (const locale of LOCALES) art.push(["kb-press", locale, svg]);
}
for (const locale of LOCALES) art.push(["vault", locale, wrap(vault.bodyFor(locale, undefined, UID), vaultView.WIDTH, vaultView.HEIGHT)]);
for (const locale of LOCALES) art.push(["omni-desk", locale, `${omni.artOf(locale, UID)}\n`]);
for (const locale of LOCALES) art.push(["credit-meter", locale, wrap(meter.sceneSvg(locale), meter.METER.width, meter.METER.height)]);

/* Every clip and mask id a drawing defines must carry the token, or two instances on one page would share it.
   The credit meter is the one exception: it appears once, on the homepage, and its CSS names its ids. */
for (const [name, , svg] of art) {
  if (name === "credit-meter") continue;
  const bare = [...svg.matchAll(/ id=["']([^"']+)["']/g)].map((m) => m[1]).filter((id) => !id.includes(UID));
  if (bare.length) throw new Error(`${name}: ids without the instance token: ${bare.join(", ")}`);
}

const hashOf = (text) => createHash("sha256").update(text).digest("hex").slice(0, 10);
const files = new Map();
const manifest = {};
for (const [name, locale, svg] of art) {
  const file = `${name}.${hashOf(svg)}.svg`;
  files.set(file, svg);
  (manifest[name] ??= {})[locale] = `/figures/${file}`;
}

const manifestText =
  `// Generated by scripts/anatomy/export.mjs from the figures' own geometry. Do not edit by hand:\n` +
  `// change the figure, then run \`node scripts/anatomy/export.mjs\` and commit public/figures/ with this file.\n` +
  `export const FIGURE_ART = ${JSON.stringify(manifest, null, 2)} as const;\n`;

const gz = async (text) => (await import("node:zlib")).gzipSync(text, { level: 9 }).length;

/* A Windows checkout with core.autocrlf turns the committed LF into CRLF; the deployed files are LF. */
const lf = (text) => text.split("\r\n").join("\n");

if (CHECK) {
  let stale = 0;
  for (const [file, svg] of files) {
    const path = join(OUT, file);
    if (!existsSync(path) || lf(readFileSync(path, "utf8")) !== svg) {
      console.log(`stale: public/figures/${file}`);
      stale++;
    }
  }
  if (!existsSync(MANIFEST) || lf(readFileSync(MANIFEST, "utf8")) !== manifestText) {
    console.log("stale: src/components/anatomy/lazy/assets.ts");
    stale++;
  }
  console.log(stale ? `figures: ${stale} stale (run node scripts/anatomy/export.mjs)` : `figures: ${files.size} files current`);
  process.exitCode = stale ? 1 : 0;
} else {
  mkdirSync(OUT, { recursive: true });
  for (const old of readdirSync(OUT)) if (old.endsWith(".svg") && !files.has(old)) unlinkSync(join(OUT, old));
  for (const [file, svg] of files) {
    writeFileSync(join(OUT, file), svg);
    console.log(`wrote public/figures/${file}  ${(svg.length / 1024).toFixed(1)} KB  gzip ${((await gz(svg)) / 1024).toFixed(1)} KB`);
  }
  writeFileSync(MANIFEST, manifestText);
  console.log("wrote src/components/anatomy/lazy/assets.ts");
}
